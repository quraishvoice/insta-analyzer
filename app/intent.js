// فرز التعليقات حسب نية الشراء — كلمات ثابتة باللهجة الخليجية والفصحى، مجاني وبدون ذكاء اصطناعي

// نوحّد الكتابة عشان «أبي» و«ابي» و«ابى» تنقرا نفس الشي
export function normalize(t) {
  return (t || "")
    .replace(/[ً-ْـ]/g, "") // التشكيل والتطويل
    .replace(/[أإآ]/g, "ا").replace(/ى/g, "ي").replace(/ة/g, "ه")
    .toLowerCase();
}

import { P, rx } from "./profile.js";

// كلمات مجالك من ملف مجالك (question_words). فاضية = أي سؤال يحسب
const NICHE = rx(P.question_words);
const OFFER = rx(P.offer_words);

const RULES = [
  ["سعر", /بكم|كم السعر|كم سعر|السعر|سعرها|سعره|الاسعار|التكلفه|تكلفه|كم الاشتراك|كم تكلف|كم قيمه|(^|[^\p{L}])(ال)?رسوم($|[^\p{L}])|\bprice\b|\bcost\b/u],
  ["تسجيل", /اسجل|نسجل|سجلني|كيف التسجيل|طريقه التسجيل|رابط التسجيل|التسجيل مفتوح|باب التسجيل|متي التسجيل|ابي اشترك|ابغي اشترك|ودي اشترك|كيف اشترك|ابي الدوره|ابغي الدوره|ودي ادخل|ابي ادخل|متي الدوره|متي تبدا|متي تبدي|موعد الدوره|الدوره الجايه|الدوره القادمه|الدفعه الجايه|فيه دوره|في دوره|عندك دوره|عندكم دوره|اونلاين|حضوري|وين مكان|وين المكان|المقاعد|الرابط|رابط|تفاصيل|ارسلت لك|ارسلتلك|راسلتك|راسلتكم|تواصلت|(^|[^\p{L}])(بال|عال|بل|ال)خاص($|[^\p{L}])|(ارسل|ارسلي|راسل|راسلني|كلمني|لي|ع|علي|في)\s+(ال)?خاص($|[^\p{L}])|^\s*خاص\s*$|واتس|رقمك|\bdm\b|ابي اتعلم|ابغي اتعلم|ودي اتعلم|كيف اتعلم|كيف ابدا/u],
  // يسأل عن اللي تبيعه بالاسم (مثل «متى الدورة؟») = يبي يسجل
  ["تسجيل", (t) => OFFER && /متي|كيف|وين|ابي|ابغي|ودي|فيه|في |عندك/.test(t) && OFFER.test(t)],
  // السؤال يحسب بس إذا كان عن مجالك، مو أي سؤال عام بالتعليقات
  ["سؤال", (t) => /[؟?]|كيف|وش |ايش|هل |متي|ليش|وين/.test(t) && (!NICHE || NICHE.test(t))],
];

// يرجع نوع النية أو null (تعليقات المدح والإيموجي ما تعتبر عميل)
export function classify(text) {
  let t = normalize(text);
  if (t.replace(/[^\p{L}]/gu, "").length < 2) return null;
  // «أسجّل صوتي» أو «أسجل بالجوال» تعني تسجيل صوت أو فيديو، مو تسجيل في العرض
  t = t.replace(/[اني]?سجل\s*(صوت|بصوت|بالجوال|بالمايك|بالبيت)\S*/g, " ");
  for (const [name, rule] of RULES) if (typeof rule === "function" ? rule(t) : rule.test(t)) return name;
  return null;
}
